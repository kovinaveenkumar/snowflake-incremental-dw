-- Step 2: role, warehouse, database, schemas and file formats.
-- Run as ACCOUNTADMIN. Cost: DW_WH is X-SMALL, starts suspended and auto-suspends after 60 s.

USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS DW_ROLE COMMENT = 'Project role for snowflake-incremental-dw';
GRANT ROLE DW_ROLE TO ROLE SYSADMIN;
GRANT ROLE DW_ROLE TO USER IDENTIFIER('{{SNOWFLAKE_USER}}');

CREATE WAREHOUSE IF NOT EXISTS DW_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  COMMENT = 'snowflake-incremental-dw';
GRANT USAGE, OPERATE, MONITOR ON WAREHOUSE DW_WH TO ROLE DW_ROLE;

-- Hard cap on trial credit use for this project.
CREATE RESOURCE MONITOR IF NOT EXISTS DW_MONITOR
  WITH CREDIT_QUOTA = 20 FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 80 PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND;
ALTER WAREHOUSE DW_WH SET RESOURCE_MONITOR = DW_MONITOR;

CREATE DATABASE IF NOT EXISTS BROKER_DW COMMENT = 'Synthetic broker data warehouse (portfolio project)';
GRANT OWNERSHIP ON DATABASE BROKER_DW TO ROLE DW_ROLE COPY CURRENT GRANTS;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE DW_ROLE;  -- needed for the Task tree in Step 8
GRANT CREATE DATABASE ON ACCOUNT TO ROLE DW_ROLE;  -- temporary BROKER_DW_TEST for Snowflake-backed tests

USE ROLE DW_ROLE;
USE DATABASE BROKER_DW;

CREATE SCHEMA IF NOT EXISTS RAW   COMMENT = 'Files as landed by Snowpipe, all text, plus load metadata';
CREATE SCHEMA IF NOT EXISTS STAGE COMMENT = 'Typed, validated rows ready to merge';
CREATE SCHEMA IF NOT EXISTS CORE  COMMENT = 'Dimensions and facts';
CREATE SCHEMA IF NOT EXISTS MART  COMMENT = 'Reporting views';
CREATE SCHEMA IF NOT EXISTS AUDIT COMMENT = 'Rejected rows, reconciliation and control totals';

CREATE FILE FORMAT IF NOT EXISTS RAW.FF_CSV
  TYPE = CSV
  SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  EMPTY_FIELD_AS_NULL = TRUE
  TRIM_SPACE = TRUE
  ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE;
